def _read(p: Path) -> list[dict]:
    if not p.exists():
        return []
    with open(p, newline="", encoding="utf-8") as h:
        return list(csv.DictReader(h))


def coverage_rows(run) -> list[dict]:
    gaps = _read(run.out / "gaps.csv")
    ye = _read(run.out / "yearend_reconciliation.csv")
    gate = {r["isin"]: r for r in _read(run.out / "reproduction_gate.csv")}
    champ = {r["isin"]: r for r in _read(run.out / "champion_models.csv")}
    out = []
    for isin, s in REGISTRY.items():
        rows = Hs.load(run.out, isin)
        st = [str(r["parse_status"]) for r in rows]
        g = [x for x in gaps if x["isin"] == isin and x["status"] == "MISSING"]
        y = [x for x in ye if x["isin"] == isin]
        out.append({"isin": isin, "ticker": s.ticker.replace("_", " "), "n": len(rows),
                    "first": rows[0]["payment_date"] if rows else "", "last": rows[-1]["payment_date"] if rows else "",
                    "gaps": len(g), "gap_list": ", ".join(x["expected_ipd"] for x in g),
                    "ok": sum(x.startswith("ok") for x in st), "derived": sum(x.startswith("DERIVED") for x in st),
                    "partial": sum(x.startswith("PARTIAL") for x in st),
                    "review": sum(x.startswith(("review", "FAIL", "ERROR")) for x in st),
                    "yearend": f"{sum(x['result'] == 'TIED' for x in y)} tied / {sum(x['result'] == 'BREAK' for x in y)} break / {len(y)}",
                    "gate": gate.get(isin, {}).get("gate_status", ""),
                    "model": champ.get(isin, {}).get("status", ""),
                    "manual": isin in MANUAL})
    return out


def write_coverage(run, cov):
    lines = ["# Coverage (issuer-reported IPDs)", "",
             f"Generated by `python -m rmbs.run` (valuation date {run.vdate}). Source of every row: `source_url` in "
             "`out/<ISIN>_<ticker>.csv`. Gaps = expected IPDs (prospectus calendar, first IPD to the latest published "
             "report) with no filing held; full list in `out/gaps.csv`.", "",
             "| ISIN | ticker | IPDs | first | last | gaps | ok | derived | partial | review | year-ends (tied/break/total) | gate | model |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in cov:
        lines.append(f"| {c['isin']} | {c['ticker']} | {c['n']} | {c['first']} | {c['last']} | {c['gaps']} | {c['ok']} | "
                     f"{c['derived']} | {c['partial']} | {c['review']} | {c['yearend']} | {c['gate']} | {c['model']} |")
    lines += ["", "## Gap lists", ""]
    for c in cov:
        if c["gap_list"]:
            gl = c["gap_list"].split(", ")
            lines.append(f"- **{c['ticker']}** ({len(gl)}): {', '.join(gl[:60])}{' ...' if len(gl) > 60 else ''}")
    stage = _read(run.out / "stage_status.csv") or run.stage_status
    lines += ["", "## Last run", ""] + [f"- {s['stage']}: {s['status']} - {s['detail']}" for s in run.stage_status]
    (run.root / "COVERAGE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def svg_fan(fan: list[dict], metric: str, title: str, w=640, h=220) -> str:
    pts = [r for r in fan if r["metric"] == metric]
    if not pts:
        return "<p class=mut>No fan chart (no model could be fitted).</p>"
    ys = [float(r[k]) for r in pts for k in ("p5", "p95")]
    lo, hi = min(ys), max(ys) or 1.0
    n = len(pts)
    px = lambda i: 50 + (w - 70) * i / max(n - 1, 1)
    py = lambda v: 10 + (h - 40) * (1 - (float(v) - lo) / ((hi - lo) or 1))
    def band(a, b):
        up = " ".join(f"{px(i):.1f},{py(r[a]):.1f}" for i, r in enumerate(pts))
        dn = " ".join(f"{px(i):.1f},{py(r[b]):.1f}" for i, r in reversed(list(enumerate(pts))))
        return up + " " + dn
    med = " ".join(f"{px(i):.1f},{py(r['p50']):.1f}" for i, r in enumerate(pts))
    ticks = "".join(f'<text x="{px(i):.1f}" y="{h - 8}" font-size="10" text-anchor="middle" fill="var(--mut)">{pts[i]["payment_date"][:7]}</text>'
                    for i in range(0, n, max(1, n // 6)))
    ylab = "".join(f'<text x="46" y="{py(v) + 3:.1f}" font-size="10" text-anchor="end" fill="var(--mut)">{v / 1e6:,.1f}m</text>'
                   for v in (lo, (lo + hi) / 2, hi))
    return (f'<figure><figcaption>{html.escape(title)}</figcaption><svg viewBox="0 0 {w} {h}" width="100%" role="img" '
            f'aria-label="{html.escape(title)}"><polygon points="{band("p5", "p95")}" fill="var(--band1)"/>'
            f'<polygon points="{band("p25", "p75")}" fill="var(--band2)"/><polyline points="{med}" fill="none" '
            f'stroke="var(--med)" stroke-width="2"/>{ticks}{ylab}</svg></figure>')


def _num(v, nd=2):
    try:
        f = float(v)
    except (TypeError, ValueError):
        return html.escape(str(v))
    return "" if math.isnan(f) else f"{f:,.{nd}f}"


def write_isin_page(run, isin, cov):
    s = REGISTRY[isin]
    rows = Hs.load(run.out, isin)
    gate = next((r for r in _read(run.out / "reproduction_gate.csv") if r["isin"] == isin), {})
    champ = next((r for r in _read(run.out / "champion_models.csv") if r["isin"] == isin), {})
    fan = _read(run.out / "uncertainty" / f"{isin}.csv")
    bbg = [r for r in _read(run.out / "bbg_vs_model.csv") if r["isin"] == isin]
    scores = _read(run.out / "model_scores" / f"{isin}.csv")
    c = next(x for x in cov if x["isin"] == isin)
    cft_rank = _read(run.out / "cft" / f"{isin}_ranking.csv")[:10]
    cft_sum = next((r for r in _read(run.out / "cft" / "summary.csv") if r["isin"] == isin), {})
    cft_html = "<p class=mut>Not ranked (no filed state).</p>" if not cft_rank else (
        f"<p>{html.escape(cft_sum.get('status', ''))}; {cft_sum.get('n_configs', '')} configurations; equivalence class "
        f"{cft_sum.get('equivalence_class_size', '')} (WAL {_num(cft_sum.get('equiv_wal_min'))}-{_num(cft_sum.get('equiv_wal_max'))}y); "
        f"filing facts used: {html.escape(cft_sum.get('filed_facts_used', ''))}; out-of-sample Spearman(S, error) "
        f"{_num(cft_sum.get('criterion_mean_spearman'))}, smoothest beats naive {cft_sum.get('criterion_smoothest_beats_naive', '')}</p>"
        "<div class=wrap><table><tr><th>#</th><th>S</th><th>prepay</th><th>default</th><th>sev</th><th>lag</th><th>call</th>"
        "<th>trigger</th><th>WAL</th><th>DM@ref</th></tr>" + "".join(
            f"<tr><td>{r['rank']}</td><td>{_num(r['S'], 3)}</td><td>{html.escape(r['prepay'])}</td><td>{html.escape(r['default'])}</td>"
            f"<td>{r['severity']}</td><td>{r['lag_m']}</td><td>{r['call']}</td><td>{r['trigger']}</td><td>{_num(r['wal_years'])}</td>"
            f"<td>{_num(r['dm_bp_at_ref'], 1)}</td></tr>" for r in cft_rank) + "</table></div>")
