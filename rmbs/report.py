def write_findings(run):
    """Auto section of docs/FINDINGS.md (between markers); the curated section above it is preserved."""
    p = run.root / "docs" / "FINDINGS.md"
    head = p.read_text(encoding="utf-8").split("<!-- AUTO -->")[0] if p.exists() else "# Findings\n\n"
    ye = [r for r in _read(run.out / "yearend_reconciliation.csv") if r["result"] == "BREAK"]
    cal = [r for r in _read(run.out / "calendar_checks.csv") if r["result"] != "EXACT"]
    val = [r for r in _read(run.out / "validation.csv") if r["result"] in ("FAIL", "BREAK")]
    lines = ["<!-- AUTO -->", "## Automatic checks (regenerated every run)", "",
             f"- Failed row/chain checks: {len(val)}"] + [f"  - {r['isin']} {r['payment_date']} {r['check']}: {r['detail']}" for r in val[:40]]
    lines += [f"- Year-end breaks: {len(ye)}"] + [f"  - {r['isin']} {r['date']}: chain {r['chain_kEUR']} vs audited {r['checkpoint_kEUR']} kEUR ({r['source_url']})" for r in ye]
    lines += [f"- IPD calendar deviations (observed vs prospectus rule): {len(cal)}"] + [f"  - {r['isin']} {r['observed']} vs rule {r['projected']}: {r['result']}" for r in cal[:40]]
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(head.rstrip() + "\n\n" + "\n".join(lines) + "\n", encoding="utf-8")


def write_zip(run) -> int:
    """RMBS_reports_ALL.zip: every source PDF under reports/, the text captures, the manifest and the download log.
    Fixed timestamps + sorted entries -> byte-stable archive."""
    import zipfile
    files = sorted(run.reports.rglob("*.pdf")) + sorted((run.root / "captures").rglob("*.txt"))
    extra = [run.root / "filing_locations.csv", run.root / "download_log.csv"]
    n = 0
    with zipfile.ZipFile(run.root / "RMBS_reports_ALL.zip", "w", zipfile.ZIP_DEFLATED) as z:
        for p in files + [e for e in extra if e.exists()]:
            zi = zipfile.ZipInfo(str(p.relative_to(run.root)), date_time=(2026, 1, 1, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(zi, p.read_bytes())
            n += p.suffix == ".pdf"
    return n


def write_all(run):
    cov = coverage_rows(run)
    write_coverage(run, cov)
    for isin in REGISTRY:
        write_isin_page(run, isin, cov)
    write_index(run, cov)
    write_findings(run)
    write_zip(run)
